// backend/routes/studentExport.js
const express = require("express");
const router = express.Router();
const db = require("../db");
const verifyToken = require("../middleware/authmiddleware");
const PDFDocument = require('pdfkit');
const { Parser } = require('json2csv');

/* =========================================================================
 * PDF DESIGN SYSTEM
 * Shared tokens + drawing helpers for the journal and assessment PDF exports
 * below, matching the visual language already used in the Lumora wellness
 * report (same palette, section headings, cards, and footer treatment) so
 * every PDF a student or counsellor downloads feels consistent. Purely
 * presentational — does not touch routes, queries, auth checks, response
 * headers, filenames, or the CSV export endpoints further down this file.
 * ========================================================================= */

const PDF_COLORS = {
  primary:      '#4F46E5',
  primaryLight: '#EEF2FF',
  danger:       '#DC2626',
  dangerLight:  '#FEF2F2',
  warning:      '#D97706',
  warningLight: '#FFFBEB',
  success:      '#16A34A',
  successLight: '#F0FDF4',
  text:         '#111827',
  textMuted:    '#6B7280',
  textLight:    '#9CA3AF',
  border:       '#E5E7EB',
  bg:           '#F9FAFB',
  white:        '#FFFFFF',
};

const PDF_PAGE_W = 595.28;          // A4 width in points
const PDF_PAGE_H = 841.89;          // A4 height in points
const PDF_MARGIN = 50;
const PDF_CONTENT_W = PDF_PAGE_W - PDF_MARGIN * 2;
const PDF_MAX_Y = PDF_PAGE_H - 50;  // leave room for the footer

function pdfFmtDate(val) {
  if (!val) return '—';
  try { return new Date(val).toLocaleDateString('en-GB'); } catch { return '—'; }
}

function pdfFmtDateTime(val) {
  if (!val) return '—';
  try {
    return new Date(val).toLocaleString('en-US', {
      month: 'long', day: 'numeric', year: 'numeric', hour: '2-digit', minute: '2-digit'
    });
  } catch { return '—'; }
}

function pdfRule(doc, y, color = PDF_COLORS.border) {
  doc.save().lineWidth(0.5).strokeColor(color)
     .moveTo(PDF_MARGIN, y).lineTo(PDF_PAGE_W - PDF_MARGIN, y).stroke().restore();
}

function pdfFilledBox(doc, x, y, w, h, fillColor, strokeColor) {
  doc.save().rect(x, y, w, h).fill(fillColor);
  if (strokeColor) doc.rect(x, y, w, h).stroke(strokeColor);
  doc.restore();
}

function pdfSectionHeading(doc, text, y) {
  doc.save().rect(PDF_MARGIN, y, 3, 14).fill(PDF_COLORS.primary).restore();
  doc.fontSize(11).font('Helvetica-Bold').fillColor(PDF_COLORS.text).text(text, PDF_MARGIN + 10, y + 1);
  return y + 22;
}

// Full-bleed brand header band drawn at the top of the first page.
// Returns the y-position where body content should resume.
function pdfHeaderBand(doc, title, subtitle) {
  doc.save().rect(0, 0, PDF_PAGE_W, 86).fill(PDF_COLORS.primary).restore();
  doc.fontSize(18).font('Helvetica-Bold').fillColor(PDF_COLORS.white)
     .text('Lumora', PDF_MARGIN, 20);
  doc.fontSize(9).font('Helvetica').fillColor('#E0E7FF')
     .text('Mental Health Support Platform', PDF_MARGIN, 43);
  doc.fontSize(13).font('Helvetica-Bold').fillColor(PDF_COLORS.white)
     .text(title, PDF_MARGIN, 61);
  if (subtitle) {
    doc.fontSize(9).font('Helvetica').fillColor('#E0E7FF')
       .text(subtitle, PDF_PAGE_W - PDF_MARGIN - 220, 63, { width: 220, align: 'right' });
  }
  return 106;
}

// Ensures `neededHeight` fits before the page's max content y; if not, starts
// a new page (with a small continuation label) and returns the y to draw at.
function pdfEnsureSpace(doc, y, neededHeight, continuationLabel) {
  if (y + neededHeight <= PDF_MAX_Y) return y;
  doc.addPage();
  let ny = 40;
  if (continuationLabel) {
    doc.fontSize(8).font('Helvetica').fillColor(PDF_COLORS.textLight)
       .text(continuationLabel, PDF_MARGIN, ny, { width: PDF_CONTENT_W, align: 'right' });
    ny += 16;
  }
  return ny;
}

function pdfFooter(doc, generatedAtLabel, note) {
  doc.fontSize(7).font('Helvetica').fillColor(PDF_COLORS.textLight)
     .text(`Generated by Lumora • ${generatedAtLabel}${note ? ` • ${note}` : ''}`, PDF_MARGIN, PDF_PAGE_H - 34, {
       align: 'center', width: PDF_CONTENT_W
     });
}

