// 4. EXPORT ASSESSMENT RESULT AS PDF
// ============================================

router.get("/assessment/:assessment_id/pdf", verifyToken, async (req, res) => {
  const assessmentId = parseInt(req.params.assessment_id);
  const userId = req.user.id;

  try {
    const [assessments] = await db.promise().query(
      "SELECT * FROM assessments WHERE id = ? AND user_id = ?",
      [assessmentId, userId]
    );

    if (assessments.length === 0) {
      return res.status(404).json({ msg: "Assessment not found" });
    }

    const assessment = assessments[0];
    let answers = [];
    try {
      answers = JSON.parse(assessment.answers);
    } catch (e) {
      answers = [];
    }

    let questions = [];
    if (assessment.type === 'phq9') {
      questions = [
        "Little interest or pleasure in doing things",
        "Feeling down, depressed, or hopeless",
        "Trouble falling/staying asleep or sleeping too much",
        "Feeling tired or having little energy",
        "Poor appetite or overeating",
        "Feeling bad about yourself or that you're a failure",
        "Trouble concentrating on things",
        "Moving or speaking slowly, or being fidgety/restless",
        "Thoughts that you would be better off dead or hurting yourself"
      ];
    } else if (assessment.type === 'gad7') {
      questions = [
        "Feeling nervous, anxious, or on edge",
        "Not being able to stop or control worrying",
        "Worrying too much about different things",
        "Trouble relaxing",
        "Being so restless that it's hard to sit still",
        "Becoming easily annoyed or irritable",
        "Feeling afraid as if something awful might happen"
      ];
    } else if (assessment.type === 'pss') {
      questions = [
        "In the last month, how often have you been upset because of something that happened unexpectedly?",
        "In the last month, how often have you felt that you were unable to control the important things in your life?",
        "In the last month, how often have you felt nervous and 'stressed'?",
        "In the last month, how often have you felt confident about your ability to handle your personal problems?",
        "In the last month, how often have you felt that things were going your way?",
        "In the last month, how often have you found that you could not cope with all the things that you had to do?",
        "In the last month, how often have you been able to control irritations in your life?",
        "In the last month, how often have you felt that you were on top of things?",
        "In the last month, how often have you been angered because of things that happened that were outside of your control?",
        "In the last month, how often have you felt difficulties were piling up so high that you could not overcome them?"
      ];
    }

    const scoreOptions = assessment.type === 'pss'
      ? ['Never', 'Almost never', 'Sometimes', 'Fairly often', 'Very often']
      : ['Not at all', 'Several days', 'More than half the days', 'Nearly every day'];

    const maxScore = questions.length ? questions.length * (scoreOptions.length - 1) : null;

    const doc = new PDFDocument({ margin: PDF_MARGIN, size: 'A4' });
    const filename = `assessment_${assessment.type}_${assessment.id}.pdf`;

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

    doc.pipe(res);

    const typeLabel = assessment.type ? assessment.type.toUpperCase() : 'Assessment';
    let y = pdfHeaderBand(doc, 'Assessment Results', typeLabel);

    // ── Score summary card ─────────────────────────────────────────────────
    const severityColorMap = {
      minimal: PDF_COLORS.success, low: PDF_COLORS.success,
      mild: PDF_COLORS.warning, moderate: PDF_COLORS.warning,
      moderately: PDF_COLORS.danger, severe: PDF_COLORS.danger, high: PDF_COLORS.danger,
    };
    const severityKey = (assessment.severity || '').trim().split(' ')[0].toLowerCase();
    const sevColor = severityColorMap[severityKey] || PDF_COLORS.textMuted;

    pdfFilledBox(doc, PDF_MARGIN, y, PDF_CONTENT_W, 74, PDF_COLORS.bg, PDF_COLORS.border);

    doc.fontSize(9).font('Helvetica').fillColor(PDF_COLORS.textMuted)
       .text('Total Score', PDF_MARGIN + 16, y + 14);
    doc.fontSize(26).font('Helvetica-Bold').fillColor(PDF_COLORS.primary)
       .text(`${assessment.score}${maxScore ? ` / ${maxScore}` : ''}`, PDF_MARGIN + 16, y + 30);

    doc.fontSize(9).font('Helvetica').fillColor(PDF_COLORS.textMuted)
       .text('Date Taken', PDF_MARGIN + 230, y + 14);
    doc.fontSize(12).font('Helvetica-Bold').fillColor(PDF_COLORS.text)
       .text(pdfFmtDate(assessment.taken_at), PDF_MARGIN + 230, y + 32);

    const badgeW = 130;
    pdfFilledBox(doc, PDF_PAGE_W - PDF_MARGIN - badgeW - 12, y + 22, badgeW, 28, sevColor, null);
    doc.fontSize(10).font('Helvetica-Bold').fillColor(PDF_COLORS.white)
       .text((assessment.severity || 'N/A').toUpperCase(), PDF_PAGE_W - PDF_MARGIN - badgeW - 12, y + 31, { width: badgeW, align: 'center' });

    y += 90;

    // ── Detailed results table ────────────────────────────────────────────
    y = pdfSectionHeading(doc, 'DETAILED RESULTS', y);

    if (questions.length === 0) {
      doc.fontSize(9).font('Helvetica').fillColor(PDF_COLORS.textMuted)
         .text('No detailed question data available for this assessment type.', PDF_MARGIN, y);
      y += 16;
    } else {
      const qColW = PDF_CONTENT_W - 150;
      const aColW = 150;

      pdfFilledBox(doc, PDF_MARGIN, y, PDF_CONTENT_W, 18, PDF_COLORS.primaryLight, null);
      doc.fontSize(8).font('Helvetica-Bold').fillColor(PDF_COLORS.primary)
         .text('QUESTION', PDF_MARGIN + 8, y + 5, { width: qColW });
      doc.fontSize(8).font('Helvetica-Bold').fillColor(PDF_COLORS.primary)
         .text('RESPONSE', PDF_MARGIN + 8 + qColW, y + 5, { width: aColW - 16, align: 'right' });
      y += 18;

      const answerChipColor = (val) => {
        if (typeof val !== 'number' || isNaN(val)) return PDF_COLORS.textMuted;
        const ratio = val / (scoreOptions.length - 1);
        if (ratio <= 0.25) return PDF_COLORS.success;
        if (ratio <= 0.5) return PDF_COLORS.textMuted;
        if (ratio <= 0.75) return PDF_COLORS.warning;
        return PDF_COLORS.danger;
      };

      questions.forEach((q, index) => {
        const answer = answers[index] !== undefined ? answers[index] : 'N/A';
        const answerText = scoreOptions[answer] || 'N/A';
        const qText = `${index + 1}. ${q}`;
        const qHeight = doc.heightOfString(qText, { width: qColW - 8, lineGap: 2 });
        const rowH = Math.max(22, qHeight + 12);

        y = pdfEnsureSpace(doc, y, rowH, `Detailed Results (continued) — ${typeLabel}`);

        const rowBg = index % 2 === 0 ? PDF_COLORS.white : PDF_COLORS.bg;
        pdfFilledBox(doc, PDF_MARGIN, y, PDF_CONTENT_W, rowH, rowBg, null);

        doc.fontSize(9).font('Helvetica').fillColor(PDF_COLORS.text)
           .text(qText, PDF_MARGIN + 8, y + 6, { width: qColW - 8, lineGap: 2 });

        doc.fontSize(9).font('Helvetica-Bold').fillColor(answerChipColor(answer))
           .text(answerText, PDF_MARGIN + 8 + qColW, y + 6, { width: aColW - 16, align: 'right' });

        pdfRule(doc, y + rowH);
        y += rowH;
      });
    }

    y += 16;

    // ── Interpretation note ───────────────────────────────────────────────
    const noteText = 'This assessment is a self-report screening tool and does not constitute a clinical diagnosis. Please review results together with the student and, where appropriate, a licensed mental health professional.';
    const noteHeight = doc.heightOfString(noteText, { width: PDF_CONTENT_W - 24, lineGap: 2 });
    const noteBoxHeight = noteHeight + 20;

    y = pdfEnsureSpace(doc, y, noteBoxHeight, `Assessment Results (continued) — ${typeLabel}`);
    pdfFilledBox(doc, PDF_MARGIN, y, PDF_CONTENT_W, noteBoxHeight, PDF_COLORS.primaryLight, PDF_COLORS.border);
    doc.fontSize(8).font('Helvetica').fillColor(PDF_COLORS.textMuted)
       .text(noteText, PDF_MARGIN + 12, y + 10, { width: PDF_CONTENT_W - 24, lineGap: 2 });

    pdfFooter(doc, pdfFmtDateTime(new Date()));

    doc.end();
  } catch (error) {
    console.error("Export assessment error:", error);
    res.status(500).json({ msg: "Failed to export assessment" });
  }
});

