// 1. EXPORT JOURNAL ENTRIES AS PDF
// ============================================

router.get("/journal/:user_id/pdf", verifyToken, async (req, res) => {
  const userId = parseInt(req.params.user_id);
  const { month, year } = req.query;

  if (req.user.id !== userId) {
    return res.status(403).json({ msg: "Unauthorized" });
  }

  try {
    let query = "SELECT * FROM journals WHERE user_id = ?";
    let params = [userId];

    if (month && year) {
      query += " AND MONTH(created_at) = ? AND YEAR(created_at) = ?";
      params.push(parseInt(month), parseInt(year));
    }

    query += " ORDER BY created_at DESC";

    const [journals] = await db.promise().query(query, params);

    if (journals.length === 0) {
      return res.status(404).json({ msg: "No journal entries found for this period" });
    }

    const doc = new PDFDocument({ margin: PDF_MARGIN, size: 'A4' });
    const filename = `journal_entries_${month || 'all'}_${year || 'all'}.pdf`;

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);

    doc.pipe(res);

    const periodLabel = (month && year)
      ? `${new Date(year, month - 1).toLocaleString('default', { month: 'long' })} ${year}`
      : 'All Entries';

    let y = pdfHeaderBand(doc, 'Journal Entries', periodLabel);

    // Meta strip
    pdfFilledBox(doc, PDF_MARGIN, y, PDF_CONTENT_W, 30, PDF_COLORS.bg, PDF_COLORS.border);
    doc.fontSize(9).font('Helvetica-Bold').fillColor(PDF_COLORS.text)
       .text(`${journals.length} ${journals.length === 1 ? 'Entry' : 'Entries'}`, PDF_MARGIN + 12, y + 10);
    doc.fontSize(9).font('Helvetica').fillColor(PDF_COLORS.textMuted)
       .text(`Exported on ${pdfFmtDate(new Date())}`, PDF_PAGE_W - PDF_MARGIN - 200, y + 10, { width: 188, align: 'right' });
    y += 46;

    journals.forEach((journal, index) => {
      const dateLabel = pdfFmtDateTime(journal.created_at);
      const contentWidth = PDF_CONTENT_W - 24;
      const contentHeight = doc.heightOfString(journal.content || '', { width: contentWidth, lineGap: 3 });
      const cardHeight = 30 + contentHeight + 16;
      const fitsWithFreshPage = cardHeight <= (PDF_MAX_Y - 40);

      if (fitsWithFreshPage) {
        y = pdfEnsureSpace(doc, y, cardHeight, `Journal Entries (continued) — ${periodLabel}`);

        pdfFilledBox(doc, PDF_MARGIN, y, PDF_CONTENT_W, cardHeight, PDF_COLORS.bg, PDF_COLORS.border);
        doc.save().rect(PDF_MARGIN, y, 3, cardHeight).fill(PDF_COLORS.primary).restore();

        doc.fontSize(10).font('Helvetica-Bold').fillColor(PDF_COLORS.primary)
           .text(`Entry ${index + 1}`, PDF_MARGIN + 12, y + 10);
        doc.fontSize(8).font('Helvetica').fillColor(PDF_COLORS.textMuted)
           .text(dateLabel, PDF_PAGE_W - PDF_MARGIN - 200, y + 11, { width: 188, align: 'right' });

        pdfRule(doc, y + 26, PDF_COLORS.border);

        doc.fontSize(10).font('Helvetica').fillColor(PDF_COLORS.text)
           .text(journal.content || '', PDF_MARGIN + 12, y + 34, { width: contentWidth, lineGap: 3 });

        y += cardHeight + 10;
      } else {
        // Very long entry: fall back to plain flowing text so PDFKit can
        // paginate it safely across multiple pages without a clipped card.
        y = pdfEnsureSpace(doc, y, 40, `Journal Entries (continued) — ${periodLabel}`);

        doc.fontSize(10).font('Helvetica-Bold').fillColor(PDF_COLORS.primary)
           .text(`Entry ${index + 1}`, PDF_MARGIN, y);
        doc.fontSize(8).font('Helvetica').fillColor(PDF_COLORS.textMuted)
           .text(dateLabel, PDF_MARGIN, y + 14);
        pdfRule(doc, y + 28);
        doc.fontSize(10).font('Helvetica').fillColor(PDF_COLORS.text)
           .text(journal.content || '', PDF_MARGIN, y + 36, { width: PDF_CONTENT_W, lineGap: 3 });

        y = doc.y + 14;
      }
    });

    pdfFooter(doc, pdfFmtDateTime(new Date()));

    doc.end();
  } catch (error) {
    console.error("Export journal error:", error);
    res.status(500).json({ msg: "Failed to export journal entries" });
  }
});

